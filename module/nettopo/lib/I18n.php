	public static function lang(): string {
		$lang = CWebUser::$data['lang'] ?? 'en_US';

		return is_string($lang) ? $lang : 'en_US';
	}

	public static function isPortuguese(): bool {
		return strpos(self::lang(), 'pt') === 0;
	}

	/**
	 * Translate a string; extra arguments are used like sprintf with numbered placeholders (%1$s).
	 */
	public static function t(string $string, ...$args): string {
		$translated = (self::isPortuguese() && array_key_exists($string, self::PT_BR)) ? self::PT_BR[$string] : $string;

		return $args ? vsprintf($translated, $args) : $translated;
	}

	/**
	 * All strings for the JavaScript client.
	 */
	public static function all(): array {
		$result = [];

		foreach (array_keys(self::PT_BR) as $string) {
			$result[$string] = self::t($string);
		}

		return $result;
	}
